CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(24) NOT NULL UNIQUE,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(10) NOT NULL DEFAULT 'USER' CHECK (role IN ('USER', 'ADMIN')),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    token_version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE user_profiles (
    user_id BIGINT PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    full_name VARCHAR(80) NOT NULL,
    bio VARCHAR(280) NOT NULL DEFAULT '',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE problems (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(100) NOT NULL,
    slug VARCHAR(100) NOT NULL UNIQUE,
    description TEXT NOT NULL,
    difficulty VARCHAR(10) NOT NULL CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD')),
    category VARCHAR(40) NOT NULL,
    input_format TEXT NOT NULL,
    output_format TEXT NOT NULL,
    constraints_text TEXT NOT NULL,
    explanation TEXT NOT NULL DEFAULT '',
    time_limit_ms INTEGER NOT NULL DEFAULT 2000 CHECK (time_limit_ms BETWEEN 500 AND 5000),
    memory_limit_mb INTEGER NOT NULL DEFAULT 128 CHECK (memory_limit_mb BETWEEN 64 AND 512),
    published BOOLEAN NOT NULL DEFAULT FALSE,
    archived BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE problem_test_cases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    problem_id BIGINT NOT NULL REFERENCES problems (id) ON DELETE CASCADE,
    position INTEGER NOT NULL CHECK (position > 0),
    input_text TEXT NOT NULL,
    expected_output TEXT NOT NULL,
    visible BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (problem_id, position)
);

CREATE TABLE submissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id),
    problem_id BIGINT NOT NULL REFERENCES problems (id),
    language VARCHAR(10) NOT NULL CHECK (language IN ('JAVA', 'PYTHON', 'CPP')),
    mode VARCHAR(10) NOT NULL CHECK (mode IN ('RUN', 'SUBMIT')),
    code TEXT NOT NULL,
    verdict VARCHAR(30) NOT NULL DEFAULT 'PENDING' CHECK (verdict IN (
        'PENDING', 'RUNNING', 'ACCEPTED', 'WRONG_ANSWER', 'COMPILATION_ERROR', 'RUNTIME_ERROR',
        'TIME_LIMIT_EXCEEDED', 'MEMORY_LIMIT_EXCEEDED', 'INTERNAL_ERROR'
    )),
    elapsed_ms INTEGER,
    memory_kb INTEGER,
    passed_cases INTEGER,
    total_cases INTEGER,
    details JSONB,
    diagnostic TEXT,
    job_payload JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ
);

CREATE TABLE contests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description TEXT NOT NULL,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL CHECK (ends_at > starts_at),
    penalty_minutes INTEGER NOT NULL DEFAULT 20 CHECK (penalty_minutes BETWEEN 0 AND 120),
    state VARCHAR(12) NOT NULL DEFAULT 'DRAFT' CHECK (state IN ('DRAFT', 'PUBLISHED', 'CANCELLED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE contest_problems (
    contest_id BIGINT NOT NULL REFERENCES contests (id) ON DELETE CASCADE,
    problem_id BIGINT NOT NULL REFERENCES problems (id),
    position INTEGER NOT NULL CHECK (position > 0),
    points INTEGER NOT NULL CHECK (points BETWEEN 1 AND 1000),
    PRIMARY KEY (contest_id, problem_id),
    UNIQUE (contest_id, position)
);

CREATE TABLE contest_participants (
    contest_id BIGINT NOT NULL REFERENCES contests (id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users (id),
    registered_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (contest_id, user_id)
);

CREATE TABLE contest_submissions (
    submission_id BIGINT PRIMARY KEY REFERENCES submissions (id) ON DELETE CASCADE,
    contest_id BIGINT NOT NULL REFERENCES contests (id)
);

CREATE TABLE achievements (
    code VARCHAR(30) PRIMARY KEY,
    name VARCHAR(60) NOT NULL,
    description VARCHAR(160) NOT NULL
);

CREATE TABLE user_achievements (
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    achievement_code VARCHAR(30) NOT NULL REFERENCES achievements (code),
    earned_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, achievement_code)
);

CREATE VIEW user_activity AS
SELECT id AS submission_id, user_id, created_at AS occurred_at, verdict, language
FROM submissions WHERE mode = 'SUBMIT';

CREATE INDEX problems_browse_idx ON problems (difficulty, category, created_at DESC) WHERE published AND NOT archived;
CREATE INDEX submissions_user_idx ON submissions (user_id, created_at DESC, id DESC);
CREATE INDEX submissions_problem_idx ON submissions (problem_id, verdict) WHERE mode = 'SUBMIT';
CREATE INDEX submissions_leaderboard_idx ON submissions (created_at, user_id, problem_id) WHERE mode = 'SUBMIT';
CREATE INDEX submissions_queue_idx ON submissions (verdict, id) WHERE verdict IN ('PENDING', 'RUNNING');
CREATE INDEX contests_schedule_idx ON contests (state, starts_at, ends_at);
CREATE INDEX contest_participants_user_idx ON contest_participants (user_id, contest_id);
CREATE INDEX contest_submissions_contest_idx ON contest_submissions (contest_id, submission_id);
CREATE INDEX contest_problems_problem_idx ON contest_problems (problem_id);
